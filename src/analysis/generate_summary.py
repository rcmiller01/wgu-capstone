"""
generate_summary.py
-------------------
Generate summary report for CohortFact_VA table.

Purpose:
- Load final CohortFact_VA table
- Generate summary statistics (row count, month range, NA columns)
- Create markdown report for user review

Output:
- Row count
- Month range (min/max period_id)
- NA percentages by column
- Sample records

Usage:
    python src/analysis/generate_summary.py
"""

import os
from pathlib import Path
import pandas as pd
from datetime import datetime


def generate_summary(cohort_fact_path: str = 'data/processed/cohort_fact_va.parquet') -> str:
    """
    Generate summary report for CohortFact_VA.
    
    Args:
        cohort_fact_path: Path to CohortFact_VA parquet file
        
    Returns:
        Markdown-formatted summary report
    """
    # Load data
    df = pd.read_parquet(cohort_fact_path)
    
    # Calculate statistics
    row_count = len(df)
    min_period = df['period_id'].min()
    max_period = df['period_id'].max()
    
    # NA percentages
    na_pct = (df.isna().sum() / len(df) * 100).sort_values(ascending=False)
    
    # Build markdown report
    report = []
    report.append("# CohortFact_VA Summary Report")
    report.append(f"\n**Generated**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    report.append(f"\n**Source**: `{cohort_fact_path}`")
    report.append("\n---\n")
    
    report.append("## Dataset Overview")
    report.append(f"\n- **Total Rows**: {row_count:,}")
    report.append(f"- **Period Range**: {min_period} to {max_period} ({len(df['period_id'].unique())} unique months)")
    report.append(f"- **State**: VA (Virginia)")
    report.append(f"- **Total Columns**: {len(df.columns)}")
    
    report.append("\n\n## Column NA Percentages")
    report.append("\n| Column | NA % |")
    report.append("| ------ | ---- |")
    for col, pct in na_pct.items():
        report.append(f"| {col} | {pct:.1f}% |")
    
    report.append("\n\n## Sample Records (First 10)")
    report.append("\n```")
    report.append(df.head(10).to_string(index=False))
    report.append("```")
    
    report.append("\n\n## Metric Distributions")
    
    # Synthea metrics
    if df['synthea_encounters'].notna().any():
        report.append("\n### Synthea Metrics")
        report.append(f"\n- **Encounters**: min={df['synthea_encounters'].min():.0f}, max={df['synthea_encounters'].max():.0f}, mean={df['synthea_encounters'].mean():.1f}")
        if df['synthea_dx_rate'].notna().any():
            report.append(f"- **Dx Rate**: min={df['synthea_dx_rate'].min():.2f}, max={df['synthea_dx_rate'].max():.2f}, mean={df['synthea_dx_rate'].mean():.2f} per 1k encounters")
        if df['synthea_lab_oob_rate'].notna().any():
            report.append(f"- **Lab OOB Rate**: min={df['synthea_lab_oob_rate'].min():.3f}, max={df['synthea_lab_oob_rate'].max():.3f}, mean={df['synthea_lab_oob_rate'].mean():.3f}")
    
    # NHANES metrics
    if df['nhanes_obesity_rate'].notna().any():
        report.append("\n### NHANES Metrics")
        report.append(f"\n- **Obesity Rate**: {df['nhanes_obesity_rate'].mean():.1%}")
        report.append(f"- **Smoking Rate**: {df['nhanes_smoking_rate'].mean():.1%}")
    
    # VDH metrics
    if df['vdh_case_rate_per_100k'].notna().any():
        report.append("\n### VDH Metrics")
        report.append(f"\n- **Case Rate**: {df['vdh_case_rate_per_100k'].mean():.2f} per 100k (mostly NULL)")
        report.append(f"- **Hosp Rate**: {df['vdh_hosp_rate_per_100k'].mean():.2f} per 100k (mostly NULL)")
    
    # NIH metrics
    report.append("\n### NIH Metrics")
    report.append(f"\n- **CXR Images**: All NULL (geo limitation)")
    report.append(f"- **CXR Abnormal Rate**: All NULL (geo limitation)")
    
    report.append("\n\n## Validation Flags")
    report.append(f"\n- **low_precision_time**: {df['low_precision_time'].sum()} rows ({df['low_precision_time'].mean():.1%})")
    report.append(f"- **ambiguous_geo**: {df['ambiguous_geo'].sum()} rows ({df['ambiguous_geo'].mean():.1%})")
    report.append(f"- **nih_geo_limited**: {df['nih_geo_limited'].sum()} rows ({df['nih_geo_limited'].mean():.1%})")
    
    report.append("\n\n## Next Steps")
    report.append("\n1. Review NA percentages - are they expected?")
    report.append("2. Check metric distributions - do they make clinical sense?")
    report.append("3. Validate period range - is it contiguous?")
    report.append("4. Proceed to statistical tests (Step 4) if satisfied")
    
    report.append("\n\n---")
    report.append(f"\n*Report generated by `src/analysis/generate_summary.py`*")
    
    return '\n'.join(report)


def main():
    """Generate and save summary report."""
    cohort_fact_path = 'data/processed/cohort_fact_va.parquet'
    
    if not Path(cohort_fact_path).exists():
        print(f"ERROR: CohortFact_VA file not found: {cohort_fact_path}")
        print("Run build_cohort_fact.py first to generate the table.")
        return
    
    # Generate report
    report = generate_summary(cohort_fact_path)
    
    # Save to reports/
    output_path = 'reports/cohort_fact_summary.md'
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    with open(output_path, 'w') as f:
        f.write(report)
    
    print(f"Summary report saved to: {output_path}")
    print("\n" + "=" * 80)
    print(report)
    print("=" * 80)


if __name__ == '__main__':
    main()
